// Preserve every responsive rule while deriving a legible course light palette.
const fs=require('node:fs'),path=require('node:path');
const palette={'090e15':'eef4fc','111a24':'ffffff','0d151f':'f3f7fd','253342':'d4e1ef','e3edf6':'193550','93a6b8':'617b93','58dfed':'286dde','f4ba6c':'ad6a16','ef8092':'c14359','7faafa':'286dde','bcf386':'397c34','b89aff':'7d59ba'};
function color(_,hex){
  let h=hex.toLowerCase();if(h.length===3||h.length===4)h=[...h].map(c=>c+c).join('');
  const alpha=h.slice(6),rgb=h.slice(0,6);if(palette[rgb])return '#'+palette[rgb]+alpha;
  const values=[0,2,4].map(i=>parseInt(rgb.slice(i,i+2),16)/255);
  const hi=Math.max(...values),lo=Math.min(...values),light=(hi+lo)/2;
  let mapped;
  if(light<.42){const target=.95-light*.18;mapped=values.map(c=>target+(c-light)*.22);}
  else{const target=.32+(1-light)*.12;mapped=values.map(c=>target+(c-light)*.65);}
  return '#'+mapped.map(c=>Math.round(Math.max(0,Math.min(1,c))*255).toString(16).padStart(2,'0')).join('')+alpha;
}
const source=fs.readFileSync(path.join(__dirname,'assets/styles.css'),'utf8');
fs.writeFileSync(path.join(__dirname,'assets/chapter-light.css'),'/* Generated by build-light.cjs from styles.css. */\n'+source.replace(/#([\da-f]{8}|[\da-f]{6}|[\da-f]{4}|[\da-f]{3})(?![\da-f])/gi,color));
